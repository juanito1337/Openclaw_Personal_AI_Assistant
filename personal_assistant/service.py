def _replace_discovered_nextcloud_resources(
    existing: list[Resource],
    discovered: list[Resource],
    *,
    instance_resource_id: str,
) -> list[Resource]:
    """Replace generated Nextcloud resources without duplicating registry IDs.

    User-managed resources are preserved. Resources generated by discovery are
    replaced on every run so discovery is safe to repeat.
    """
    generated_ids = {instance_resource_id, "nextcloud-files-main"}
    generated_prefixes = ("nextcloud-calendar-", "nextcloud-addressbook-")
    retained = [
        item
        for item in existing
        if item.id not in generated_ids and not item.id.startswith(generated_prefixes)
    ]
    existing_by_id = {item.id: item for item in existing}
    merged: dict[str, Resource] = {item.id: item for item in retained}
    for item in discovered:
        previous = existing_by_id.get(item.id)
        if previous and previous.connector == item.connector and previous.kind == item.kind:
            # Discovery refreshes remote metadata but never silently removes an
            # explicitly granted permission such as calendar create.
            permissions = tuple(dict.fromkeys((*item.permissions, *previous.permissions)))
            metadata = dict(item.metadata)
            if item.kind == "file-root" and previous.metadata.get("allowed_roots"):
                metadata["allowed_roots"] = previous.metadata["allowed_roots"]
            item = Resource(
                id=item.id,
                kind=item.kind,
                connector=item.connector,
                enabled=previous.enabled,
                remote_id=item.remote_id,
                permissions=permissions,
                metadata=metadata,
            )
        merged[item.id] = item
    return list(merged.values())


