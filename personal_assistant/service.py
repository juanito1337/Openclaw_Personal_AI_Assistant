    def _configure_discovered_caldav(
        self,
        *,
        component: str,
        resource_id: str,
        allow_create: bool,
        allow_read: bool,
        allow_update: bool = False,
    ):
        component = component.upper()
        collections = self.nextcloud_discovery.calendar_collections()
        selected = next((item for item in collections if item.resource_id == resource_id), None)
        if selected is None:
            raise ValueError("Unbekannte CalDAV-Ressource; zuerst das passende Discovery-Werkzeug ausfuehren")
        if not selected.supports(component):
            label = "VEVENT" if component == "VEVENT" else "VTODO"
            raise ValueError(f"Die ausgewaehlte Ressource unterstuetzt {label} nicht")
        if allow_read and not selected.can_read:
            raise PermissionError("Die ausgewaehlte Ressource ist nicht lesbar")
        if allow_create and not selected.can_create:
            raise PermissionError("Die ausgewaehlte Ressource erlaubt serverseitig kein Anlegen")
        if allow_update and not selected.can_update:
            raise PermissionError("Die ausgewaehlte Ressource erlaubt serverseitig keine Inhaltsaenderung")

        permissions: list[str] = []
        if allow_read and selected.can_read:
            permissions.append("read")
        if allow_create and selected.can_create:
            permissions.append("create")
        if allow_update and selected.can_update:
            permissions.append("update")
        resource = Resource(
            id=selected.resource_id,
            kind="calendar",
            connector="nextcloud",
            enabled=True,
            remote_id=selected.href,
            permissions=tuple(permissions),
            metadata={
                "href": selected.href,
                "name": selected.name,
                "description": selected.description,
                "components": list(selected.components),
                "discovered_privileges": list(selected.privileges),
                "server_can_read": selected.can_read,
                "server_can_create": selected.can_create,
                "server_can_update": selected.can_update,
                "discovery_source": "live-caldav",
            },
        )
        self.registry.upsert(resource)
        return selected

