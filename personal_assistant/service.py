    def discover_nextcloud(self, *, persist: bool = True) -> dict[str, Any]:
        health = self.nextcloud_discovery.root_health()
        collections = self.nextcloud_discovery.calendar_collections()
        calendars = [item for item in collections if not item.components or item.supports("VEVENT")]
        task_lists = [item for item in collections if item.supports("VTODO")]
        addressbooks = self.nextcloud_discovery.addressbooks()
        resources = list(self.registry.resources.values())
        if persist:
            discovered_resources = [
                Resource(
                    id=self.config.nextcloud.resource_id,
                    kind="nextcloud-instance",
                    connector="nextcloud",
                    enabled=True,
                    permissions=("read",),
                    metadata={"name": "Nextcloud", "url_env": self.config.nextcloud.base_url_env},
                ),
                Resource(
                    id="nextcloud-files-main",
                    kind="file-root",
                    connector="nextcloud",
                    enabled=True,
                    remote_id=self.config.nextcloud.allowed_file_roots[0]
                    if self.config.nextcloud.allowed_file_roots
                    else "Assistent",
                    permissions=("read", "create"),
                    metadata={
                        "allowed_roots": list(self.config.nextcloud.allowed_file_roots),
                        "name": "Nextcloud Dateien",
                    },
                ),
            ]
            for item in collections:
                discovered_resources.append(
                    Resource(
                        id=item.resource_id,
                        kind="calendar",
                        connector="nextcloud",
                        enabled=True,
                        remote_id=item.href,
                        permissions=("read",) if item.can_read else (),
                        metadata={
                            "href": item.href,
                            "name": item.name,
                            "description": item.description,
                            "components": list(item.components),
                            "discovered_privileges": list(item.privileges),
                            "server_can_read": item.can_read,
                            "server_can_create": item.can_create,
                            "server_can_update": item.can_update,
                        },
                    )
                )
            for item in addressbooks:
                permissions: list[str] = []
                if item.can_read:
                    permissions.append("read")
                if item.can_create:
                    permissions.append("create")
                if item.can_update:
                    permissions.append("update")
                discovered_resources.append(
                    Resource(
                        id=item.resource_id,
                        kind="addressbook",
                        connector="nextcloud",
                        enabled=True,
                        remote_id=item.href,
                        permissions=tuple(permissions),
                        metadata={
                            "href": item.href,
                            "name": item.name,
                            "description": item.description,
                            "discovered_privileges": list(item.privileges),
                            "server_can_read": item.can_read,
                            "server_can_create": item.can_create,
                            "server_can_update": item.can_update,
                        },
                    )
                )
            resources = _replace_discovered_nextcloud_resources(
                resources,
                discovered_resources,
                instance_resource_id=self.config.nextcloud.resource_id,
            )
            self.registry.write(resources)
        return {
            "health": health,
            "calendars": [self._discovered_payload(item) for item in calendars],
            "task_lists": [self._discovered_payload(item) for item in task_lists],
            "caldav_collections": [self._discovered_payload(item) for item in collections],
            "addressbooks": [asdict(item) for item in addressbooks],
            "persisted": persist,
        }

    def sync_mail(self) -> dict[str, Any]:
        projection = self.indexer.index_mail_snapshots()
        if self.role == "sync-worker":
            database: dict[str, Any] = {
                "seen": 0,
                "indexed": 0,
                "unchanged": 0,
                "skipped": "sync-worker-uses-mail-owner-projection",
                "mail_database_access": "none",
            }
        else:
            mail_db = state_paths().mail / "mail_agent.sqlite3"
            database = self.indexer.index_mail_database(mail_db)
        return {
            "database": database,
            "projection": projection,
            "snapshots": projection,
        }

    def sync_nextcloud(self) -> dict[str, Any]:
        if not self.config.nextcloud.enabled:
            return {"ok": True, "skipped": "Nextcloud ist deaktiviert"}
        # The sync role owns only the knowledge database.  The resource registry
        # belongs to the core role and is therefore deliberately mounted read-only
        # in that container.  Discovery is still live, but only an interactive
        # core-capable role may persist the refreshed registry.
        discovery = self.discover_nextcloud(persist=self.role != "sync-worker")
        calendars = self.nextcloud_discovery.calendars()
        addressbooks = self.nextcloud_discovery.addressbooks()
        files = self.nextcloud_files.sync_index(
            self.storage,
            self.indexer,
            resource_id="nextcloud-files-main",
            roots=self.config.nextcloud.allowed_file_roots,
            max_items=self.config.search.nextcloud_max_items,
            max_depth=self.config.search.nextcloud_max_depth,
        )
        contacts = self.nextcloud_contacts.sync_index(self.storage, addressbooks)
        events = self.nextcloud_calendar.sync_index(self.storage, calendars)
        return {
            "ok": bool(discovery.get("health", {}).get("ok"))
            and all(int(section.get("errors") or 0) == 0 for section in (files, contacts, events)),
            "discovery": discovery,
            "files": files,
            "contacts": contacts,
            "calendar": events,
        }

    def sync_all(self) -> dict[str, Any]:
        mail = self.sync_mail()
        projection = mail.get("projection", {})
        result = {
            "ok": bool(projection.get("published", True)),
            "mail": mail,
        }
        try:
            nextcloud = self.sync_nextcloud()
            result["nextcloud"] = nextcloud
            result["ok"] = bool(result["ok"] and nextcloud.get("ok", True))
        except Exception as exc:
            result["ok"] = False
            result["nextcloud"] = {"ok": False, "error": str(exc)}
            if self.storage.core_read_only:
                self.log.warning("Nextcloud-Sync fehlgeschlagen: %s", exc)
            else:
                self.storage.audit("sync.nextcloud_failed", {"error": str(exc)})
        return result

