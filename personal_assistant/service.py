    def task_create(
        self,
        *,
        title: str,
        due: str = "",
        start: str = "",
        description: str = "",
        priority: int = 0,
        categories: tuple[str, ...] = (),
        uid: str = "",
    ) -> dict[str, Any]:
        settings = self.tool_settings.nextcloud.tasks
        if not settings.enabled or not settings.allow_create:
            raise PermissionError("Direktes Aufgabenwerkzeug ist deaktiviert")
        title = " ".join(str(title or "").split())
        if not title:
            raise ValueError("Aufgabentitel fehlt")
        if len(title) > 200 or len(description) > 10000:
            raise ValueError("Aufgabentitel oder Beschreibung ist zu lang")
        priority = int(priority)
        if priority < 0 or priority > 9:
            raise ValueError("Prioritaet muss zwischen 0 und 9 liegen")
        cleaned_categories = tuple(
            dict.fromkeys(" ".join(str(v).split()) for v in categories if str(v).strip())
        )
        if len(cleaned_categories) > 20 or any(len(v) > 100 for v in cleaned_categories):
            raise ValueError("Zu viele oder zu lange Kategorien")

        due_value = ""
        start_value = ""
        due_local: datetime | None = None
        start_local: datetime | None = None
        due_is_date = False
        start_is_date = False
        now = datetime.now(UTC)
        if due:
            due_local, due_is_date = self._parse_task_value(due, settings.timezone)
            if due_local.astimezone(UTC) > now + timedelta(days=settings.max_future_days):
                raise ValueError(f"Faelligkeit liegt mehr als {settings.max_future_days} Tage in der Zukunft")
            due_value = (
                due_local.strftime("%Y%m%d")
                if due_is_date
                else due_local.astimezone(UTC).strftime("%Y%m%dT%H%M%SZ")
            )
        if start:
            start_local, start_is_date = self._parse_task_value(start, settings.timezone)
            start_value = (
                start_local.strftime("%Y%m%d")
                if start_is_date
                else start_local.astimezone(UTC).strftime("%Y%m%dT%H%M%SZ")
            )
        if due and start and due_is_date != start_is_date:
            raise ValueError("Start und Faelligkeit muessen beide Datum oder beide Datum/Uhrzeit sein")
        if due_local and start_local and due_local < start_local:
            raise ValueError("Faelligkeit darf nicht vor dem Aufgabenstart liegen")

        normalized = "|".join(
            [
                settings.resource_id,
                title,
                start_value,
                due_value,
                description.strip(),
                str(priority),
                ",".join(cleaned_categories),
            ]
        )
        task_uid = str(uid or "").strip() or (
            "assistant-task-" + hashlib.sha256(normalized.encode("utf-8")).hexdigest()[:32] + "@local"
        )
        lines = [
            "BEGIN:VCALENDAR",
            "VERSION:2.0",
            "PRODID:-//Personal Assistant//Direct Tasks Tool//DE",
            "CALSCALE:GREGORIAN",
            "BEGIN:VTODO",
            f"UID:{self._ics_escape(task_uid)}",
            f"DTSTAMP:{now.strftime('%Y%m%dT%H%M%SZ')}",
            f"SUMMARY:{self._ics_escape(title)}",
            "STATUS:NEEDS-ACTION",
            "PERCENT-COMPLETE:0",
        ]
        if start_value:
            prefix = "DTSTART;VALUE=DATE:" if start_is_date else "DTSTART:"
            lines.append(prefix + start_value)
        if due_value:
            prefix = "DUE;VALUE=DATE:" if due_is_date else "DUE:"
            lines.append(prefix + due_value)
        if priority:
            lines.append(f"PRIORITY:{priority}")
        if description.strip():
            lines.append(f"DESCRIPTION:{self._ics_escape(description.strip())}")
        if cleaned_categories:
            lines.append("CATEGORIES:" + ",".join(self._ics_escape(v) for v in cleaned_categories))
        lines.extend(["END:VTODO", "END:VCALENDAR", ""])
        ics = "\r\n".join(lines)

        plan = self.actions.plan(
            "tasks.create",
            settings.resource_id,
            {
                "ics": ics,
                "uid": task_uid,
                "title": title,
                "start": start_value,
                "due": due_value,
                "priority": priority,
                "categories": list(cleaned_categories),
                "direct_tasks_tool": True,
            },
            idempotency_key=(
                f"direct-tasks:{settings.resource_id}:"
                + hashlib.sha256(normalized.encode("utf-8")).hexdigest()
            ),
        )
        if plan.status in {"proposed", "failed"}:
            plan = self.actions.approve_configured_tasks_tool(
                plan.id,
                evidence={
                    "tool_enabled": True,
                    "resource_id": settings.resource_id,
                    "title_hash": hashlib.sha256(title.encode("utf-8")).hexdigest(),
                },
            )
        if plan.status not in {"approved", "completed"}:
            return {
                "ok": False,
                "action": asdict(plan),
                "detail": "Aufgaben-ActionPlan ist nicht ausfuehrbar",
            }
        result, duplicate = self.actions.execute_task_create(plan.id)
        response = {
            "ok": result.status == "completed",
            "duplicate": duplicate,
            "task_resource_id": settings.resource_id,
            "task": {
                "uid": task_uid,
                "title": title,
                "start": start_local.isoformat() if start_local else "",
                "due": due_local.isoformat() if due_local else "",
                "due_is_date": due_is_date,
                "priority": priority,
                "categories": list(cleaned_categories),
            },
            "action": asdict(result),
        }
        if result.status == "failed" and result.error:
            response["detail"] = result.error
        return response

