    def contact_update(
        self,
        *,
        uid: str,
        name: str | None = None,
        emails: tuple[str, ...] | None = None,
        phones: tuple[str, ...] | None = None,
        organization: str | None = None,
        note: str | None = None,
        expected_name: str = "",
        expected_email: str = "",
        allow_name_collision: bool = False,
    ) -> dict[str, Any]:
        settings = self.tool_settings.nextcloud.contacts
        if not settings.enabled or not settings.allow_update:
            raise PermissionError("Direktes Kontakt-Aktualisierungswerkzeug ist deaktiviert")
        clean_uid = str(uid or "").strip()
        if not clean_uid:
            raise ValueError("Kontakt-UID fehlt; zuerst contacts search verwenden")
        changes = normalize_contact_update(
            name=name,
            emails=emails,
            phones=phones,
            organization=organization,
            note=note,
        )
        resource, contacts = self._contacts_live()
        matches = [item for item in contacts if item.uid == clean_uid]
        if not matches:
            raise LookupError("Kontakt-UID wurde im konfigurierten Adressbuch nicht gefunden")
        if len(matches) != 1:
            raise RuntimeError("Kontakt-UID ist nicht eindeutig; Aktualisierung wurde abgebrochen")
        current = matches[0]
        if expected_name and " ".join(current.name.casefold().split()) != " ".join(
            expected_name.casefold().split()
        ):
            raise RuntimeError("Kontaktname stimmt nicht mehr mit --expected-name ueberein")
        if expected_email and expected_email.casefold() not in {value.casefold() for value in current.emails}:
            raise RuntimeError("Kontakt-E-Mail stimmt nicht mehr mit --expected-email ueberein")

        other_contacts = [item for item in contacts if item.href != current.href]
        if "emails" in changes:
            requested_emails = {value.casefold() for value in changes["emails"]}
            collisions = [
                item
                for item in other_contacts
                if requested_emails.intersection({value.casefold() for value in item.emails})
            ]
            if collisions:
                return {
                    "ok": False,
                    "updated": False,
                    "detail": (
                        "Mindestens eine neue E-Mail-Adresse ist bereits einem anderen Kontakt zugeordnet"
                    ),
                    "collisions": [self._contact_payload(item) for item in collisions],
                }
        if "name" in changes and not allow_name_collision:
            requested_name = " ".join(str(changes["name"]).casefold().split())
            collisions = [
                item
                for item in other_contacts
                if requested_name and " ".join(item.name.casefold().split()) == requested_name
            ]
            if collisions:
                return {
                    "ok": False,
                    "updated": False,
                    "detail": (
                        "Der neue Name ist bereits vorhanden; explizit pruefen oder "
                        "--allow-name-collision verwenden"
                    ),
                    "collisions": [self._contact_payload(item) for item in collisions],
                }

        decision = self.policy.decide(
            settings.resource_id,
            "contacts.update",
            {"direct_contacts_tool": True, "uid": clean_uid},
        )
        if not decision.allowed:
            raise PermissionError(decision.reason)
        vcard = update_vcard(current.raw, current.uid, changes)
        vcard_hash = hashlib.sha256(vcard.encode("utf-8")).hexdigest()
        plan = self.actions.plan(
            "contacts.update",
            settings.resource_id,
            {
                "uid": current.uid,
                "href": current.href,
                "etag": current.etag,
                "vcard": vcard,
                "vcard_sha256": vcard_hash,
                "changes": changes,
                "before": self._contact_edit_payload(current),
                "direct_contacts_tool": True,
                "optimistic_concurrency": True,
            },
            idempotency_key=(
                f"direct-contact-update:{settings.resource_id}:{current.uid}:"
                + hashlib.sha256((current.etag + "\0" + vcard_hash).encode("utf-8")).hexdigest()
            ),
        )
        if plan.status in {"proposed", "failed"}:
            plan = self.actions.approve_configured_contacts_update(
                plan.id,
                evidence={
                    "tool_enabled": True,
                    "resource_id": settings.resource_id,
                    "explicit_user_update": True,
                    "uid_hash": hashlib.sha256(current.uid.encode("utf-8")).hexdigest(),
                    "etag_present": bool(current.etag),
                    "changed_fields": sorted(changes),
                },
            )
        if plan.status not in {"approved", "completed"}:
            return {"ok": False, "updated": False, "action": asdict(plan)}
        result, duplicate = self.actions.execute_contact_update(plan.id)
        response: dict[str, Any] = {
            "ok": result.status == "completed",
            "updated": result.status == "completed" and not duplicate,
            "already_applied": bool(duplicate),
            "resource_id": settings.resource_id,
            "before": self._contact_edit_payload(current),
            "action": asdict(result),
        }
        if result.status == "completed":
            refreshed = self.nextcloud_contacts.read_contact(current.href, fallback_uid=current.uid)
            response["after"] = self._contact_edit_payload(refreshed)
        elif result.error:
            response["detail"] = result.error
        return response

    def contact_from_mail(
        self,
        *,
        folder: str,
        message_id: str,
        expected_subject: str = "",
        dry_run: bool = True,
        name: str = "",
        organization: str = "",
        phones: tuple[str, ...] = (),
        note: str = "",
        allow_name_collision: bool = False,
    ) -> dict[str, Any]:
        message = self.mail_move_service.read_message(
            folder,
            message_id,
            expected_subject=expected_subject,
        )
        scan = self.antivirus.scan_bytes(
            message.raw,
            name="selected-mail.eml",
            source_type="contact-from-mail",
        )
        if (
            self.tool_settings.security.antivirus.enabled
            and self.tool_settings.security.antivirus.fail_closed
            and not scan.clean
        ):
            raise PermissionError(
                "Kontaktvorschlag durch Virenscanner blockiert: "
                + (scan.signature or scan.detail or scan.status)
            )
        extracted = candidate_from_mail(message)
        selected_name = " ".join(str(name or extracted.name).split())
        selected_org = " ".join(str(organization or extracted.organization).split())
        selected_phones = tuple(phones) if phones else extracted.phones
        candidate = ContactCandidate(
            name=selected_name,
            emails=extracted.emails,
            phones=selected_phones,
            organization=selected_org,
            source="mail",
            source_hash=extracted.source_hash,
            confidence=1.0 if name else extracted.confidence,
            automated_sender=extracted.automated_sender,
            field_sources={
                **(extracted.field_sources or {}),
                **({"name": "explicit-user-input"} if name else {}),
                **({"organization": "explicit-user-input"} if organization else {}),
                **({"phone": "explicit-user-input"} if phones else {}),
            },
        )
        settings = self.tool_settings.nextcloud.contacts
        contacts: list[Any] = []
        duplicates = {"exact_email_matches": [], "same_name_matches": []}
        if settings.enabled and settings.allow_list and settings.resource_id:
            resource = self.registry.get(settings.resource_id)
            contacts = self.nextcloud_contacts.list_contacts(self._contact_collection(resource))
            duplicates = self._contact_duplicate_report(candidate, contacts)
        proposal = {
            "ok": True,
            "dry_run": bool(dry_run),
            "source_mail": {
                "folder": message.source_folder,
                "mailbox_id": message.mailbox_id,
                "subject": message.subject,
                "received_at": message.received_at,
            },
            "candidate": candidate.to_dict(),
            "duplicates": duplicates,
            "antivirus": scan.to_dict(),
            "requires_name": not bool(candidate.name),
            "automated_sender_blocked": candidate.automated_sender,
        }
        if dry_run:
            return proposal
        if candidate.automated_sender:
            proposal.update(
                {
                    "ok": False,
                    "created": False,
                    "detail": (
                        "Automatischer/no-reply-Absender wird nicht direkt als Kontakt angelegt; "
                        "contacts create fuer eine bewusste manuelle Anlage verwenden"
                    ),
                }
            )
            return proposal
        if not candidate.name:
            proposal.update(
                {
                    "ok": False,
                    "created": False,
                    "detail": "Kein belastbarer Kontaktname erkannt; --name ist erforderlich",
                }
            )
            return proposal
        created = self._create_contact_candidate(
            candidate,
            note=note or "Aus einer ausgewaehlten E-Mail uebernommen und vom Nutzer bestaetigt.",
            allow_name_collision=allow_name_collision,
        )
        return {**proposal, **created, "dry_run": False}

