    @staticmethod
    def _contact_duplicate_report(candidate: ContactCandidate, contacts: list[Any]) -> dict[str, Any]:
        emails = {value.casefold() for value in candidate.emails}
        exact = [
            contact
            for contact in contacts
            if emails.intersection({value.casefold() for value in contact.emails})
        ]
        name_key = " ".join(candidate.name.casefold().split())
        same_name = [
            contact
            for contact in contacts
            if name_key and " ".join(contact.name.casefold().split()) == name_key and contact not in exact
        ]
        return {
            "exact_email_matches": [PersonalAssistant._contact_payload(item) for item in exact],
            "same_name_matches": [PersonalAssistant._contact_payload(item) for item in same_name],
        }

    def _create_contact_candidate(
        self,
        candidate: ContactCandidate,
        *,
        note: str = "",
        allow_name_collision: bool = False,
    ) -> dict[str, Any]:
        settings = self.tool_settings.nextcloud.contacts
        if not settings.enabled or not settings.allow_create:
            raise PermissionError("Direktes Kontakt-Anlegewerkzeug ist deaktiviert")
        if not candidate.name:
            raise ValueError("Kontaktname fehlt; bei Mail-Vorschlaegen --name angeben")
        resource = self.registry.get(settings.resource_id)
        decision = self.policy.decide(
            settings.resource_id,
            "contacts.create",
            {"direct_contacts_tool": True, "create_only": True},
        )
        if not decision.allowed:
            raise PermissionError(decision.reason)
        contacts = self.nextcloud_contacts.list_contacts(self._contact_collection(resource))
        duplicates = self._contact_duplicate_report(candidate, contacts)
        if duplicates["exact_email_matches"]:
            return {
                "ok": True,
                "duplicate": True,
                "created": False,
                "candidate": candidate.to_dict(),
                "duplicates": duplicates,
                "detail": "Kontakt mit dieser E-Mail-Adresse ist bereits vorhanden",
            }
        if duplicates["same_name_matches"] and not allow_name_collision:
            return {
                "ok": False,
                "duplicate": False,
                "created": False,
                "candidate": candidate.to_dict(),
                "duplicates": duplicates,
                "detail": (
                    "Kontakt mit gleichem Namen vorhanden; explizit pruefen oder "
                    "--allow-name-collision verwenden"
                ),
            }

        identity_material = "\0".join(
            [settings.resource_id, *sorted(value.casefold() for value in candidate.emails)]
        )
        uid = "openclaw-contact-" + hashlib.sha256(identity_material.encode("utf-8")).hexdigest()[:32]
        vcard = build_vcard(candidate, uid, note=note)
        plan = self.actions.plan(
            "contacts.create",
            settings.resource_id,
            {
                "uid": uid,
                "vcard": vcard,
                "name": candidate.name,
                "emails": list(candidate.emails),
                "phones": list(candidate.phones),
                "organization": candidate.organization,
                "source": candidate.source,
                "source_hash": candidate.source_hash,
                "direct_contacts_tool": True,
                "create_only": True,
            },
            idempotency_key=(
                f"direct-contact:{settings.resource_id}:"
                + hashlib.sha256(identity_material.encode("utf-8")).hexdigest()
            ),
        )
        if plan.status in {"proposed", "failed"}:
            plan = self.actions.approve_configured_contacts_tool(
                plan.id,
                evidence={
                    "tool_enabled": True,
                    "resource_id": settings.resource_id,
                    "explicit_user_create": True,
                    "email_hashes": [
                        hashlib.sha256(value.encode("utf-8")).hexdigest() for value in candidate.emails
                    ],
                },
            )
        if plan.status not in {"approved", "completed"}:
            return {"ok": False, "created": False, "action": asdict(plan)}
        result, duplicate = self.actions.execute_contact_create(plan.id)
        response = {
            "ok": result.status == "completed",
            "duplicate": duplicate,
            "created": result.status == "completed" and not duplicate,
            "resource_id": settings.resource_id,
            "contact": {
                "uid": uid,
                "name": candidate.name,
                "emails": list(candidate.emails),
                "phones": list(candidate.phones),
                "organization": candidate.organization,
                "source": candidate.source,
            },
            "action": asdict(result),
        }
        if result.status == "failed" and result.error:
            response["detail"] = result.error
        return response

